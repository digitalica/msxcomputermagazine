// Generates docker/redirects.conf: nginx maps that send old WordPress URLs to
// their place on the new site, so deep links keep working.
//
//   node scripts/migrate/redirects.mjs
//
// Needs the old site (or the .cache/ of an earlier run) for the list of
// attachment pages. Everything else is a fixed rule below.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parse } from 'yaml';
import { OLD_SITE, fetchText } from './fetch.mjs';

const OUT = 'docker/redirects.conf';
const local = (url) => url.replace(/^https?:\/\/(www\.)?msxcomputermagazine\.nl/, '');
const re = (p) => p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Cover file -> issue page.
const issueByCover = new Map();
for (const f of await readdir('src/content/issues')) {
  const data = parse((await readFile(path.join('src/content/issues', f), 'utf8')).split(/^---$/m)[1]);
  issueByCover.set(path.basename(data.cover), `/archief/${f.replace(/\.md$/, '')}/`);
}

// Attachment pages: WordPress had a page per uploaded file, e.g. /mcm_cover001/
// or /achtergrond/wammes_1993/. Covers go to their issue, the rest to the file.
const media = [];
for (let page = 1; ; page++) {
  const json = JSON.parse(await fetchText(`${OLD_SITE}/wp-json/wp/v2/media?per_page=100&page=${page}`));
  if (!Array.isArray(json) || json.length === 0) break;
  media.push(...json);
  if (json.length < 100) break;
}
const attachments = media
  .map((m) => {
    const file = local(m.source_url);
    return [local(m.link), issueByCover.get(path.basename(file)) ?? file];
  })
  .sort(([a], [b]) => a.localeCompare(b));

// Pages by id, for /?page_id=.
const pages = JSON.parse(await fetchText(`${OLD_SITE}/wp-json/wp/v2/pages?per_page=100`));
const pageTarget = { '/contact-2/': '/contact/', '/oeps/': '/' };
const pageIds = pages.map((p) => [p.id, pageTarget[local(p.link)] ?? local(p.link)]).sort(([a], [b]) => a - b);

// Fixed rules, checked in order (first match wins).
const rules = [
  ['/contact-2', '/contact/'],
  ['/archief', '/'],
  ['/oeps', '/'],
  ['/index.php', '/'],
  ['/mcm-archive', '/'],
  ['/mcm_dzi', '/mcm-bladerkamer/'], // the old standalone viewer page
  ['/mcm_dzi/index.html', '/mcm-bladerkamer/'],
  ['/sitemap.xml', '/sitemap-index.xml'],
  ['/wp-sitemap.xml', '/sitemap-index.xml'],
];
const patterns = [
  ['^/author(/.*)?$', '/'],
  ['^/downloads(/.*)?$', '/'], // demo products of the shop plugin
  ['^/checkout(/.*)?$', '/'],
  ['^/(.+/)?feed/?$', '/feed.xml'],
  ['^/page/\\d+/?$', '/'],
  ['^/archief-categorie/([^/]+)/page/\\d+/?$', '/archief-categorie/$1/'],
  ['^/archief/([^/]+)/attachment/.*$', '/archief/$1/'],
];

const line = (from, to) => `    ${from.padEnd(58)} ${to};`;
const exact = (p) => `"~^${re(p.replace(/\/$/, ''))}/?$"`;

const conf = `# Generated by scripts/migrate/redirects.mjs - do not edit by hand.
# Old WordPress URLs -> new site (301). Included at http level; used in
# docker/nginx.conf. Paths match with and without a trailing slash.

map $uri $old_url_redirect {
    default "";

    # Pages and old site sections
${rules.map(([from, to]) => line(exact(from), to)).join('\n')}

    # WordPress patterns
${patterns.map(([from, to]) => line(`"~${from}"`, to)).join('\n')}

    # Attachment pages (${attachments.length})
${attachments.map(([from, to]) => line(exact(from), to)).join('\n')}
}

# /?page_id=<id>
map $arg_page_id $old_page_id_redirect {
    default "";
${pageIds.map(([id, to]) => line(String(id), to)).join('\n')}
}
`;

await writeFile(OUT, conf);
console.log(`${OUT}: ${rules.length + patterns.length} rules, ${attachments.length} attachment pages, ${pageIds.length} page ids`);
